/* 底盘端部挂甲与场地边界回归：检查摆放、出战检查、纸面车速和真实战斗刷新。 */
'use strict';
const assert = require('assert');
const { loadGame } = require('./evolve');

function run() {
  const { SA } = loadGame();
  assert.deepStrictEqual(JSON.parse(JSON.stringify(SA.CAMPAIGN[0].bounds)), { left: 0, right: 1280 }, '序章应有两侧边界');
  assert.deepStrictEqual(JSON.parse(JSON.stringify(SA.CAMPAIGN[2].bounds)), { left: 0, right: 1280 }, '第二章应有两侧边界');
  assert(!SA.CAMPAIGN[1].bounds, '第一章应保留自由场地');
  assert(SA.CAMPAIGN.every((chapter, i) => i === 0 || i === 2 || !chapter.bounds), '边界不能扩散到其它章节');
  const row = SA.V.chassisRow('track');
  const near = (a, b) => Math.abs(a - b) < 1e-9;
  const car = (chassis, boiler = 'boiler') => {
    const v = SA.V.create('端甲测试车');
    v.body[row][4] = SA.newCell(chassis, 1);
    v.body[row - 2][4] = SA.newCell(boiler, 1);
    v.body[row - 4][4] = SA.newCell('cockpit', 1);
    return v;
  };
  for (const chassis of ['track', 'quad']) {
    const width = SA.fp(chassis).w;
    const v = car(chassis), plain = SA.V.stats(v).topSpeed;
    assert(SA.V.canPlace(v, 'plate', row, 3).ok, `${chassis} 后端甲片应可安装`);
    assert(SA.V.canPlace(v, 'armor', row, 4 + width).ok, `${chassis} 前端铁装甲应可安装`);
    assert(SA.V.canPlace(v, 'armor_heavy', row, 2).ok, `${chassis} 后端重装甲应可安装`);
    assert(!SA.V.canPlace(v, 'tank_s', row, 3).ok, '非装甲不能进入底盘保留区');
    assert(!SA.V.canPlace(v, 'armor', row, 1).ok, '隔一格的装甲不能悬空安装');
    assert(!SA.V.canPlace(v, 'armor', row, 4).ok, '装甲不能压在底盘上');
    const chain = car(chassis);
    chain.body[row][4 + width] = SA.newCell(chassis, 1);
    assert(!SA.V.canPlace(chain, 'armor', row, 4 + width - 1).ok, '链内接缝不能挂甲');
    const gap = car(chassis);
    gap.body[row][4 + width * 2] = SA.newCell(chassis, 1);
    assert(!SA.V.canPlace(gap, 'armor', row, 4 + width).ok, '底盘断链时不能借端甲填空');
    assert(SA.V.issues(gap).some(issue => issue.reason.includes('首尾相连')), '底盘断链仍须报错');
    v.body[row][3] = SA.newCell('plate', 1);
    assert(near(SA.V.stats(v).topSpeed / plain, 0.7), '单侧挂甲应减速 30%');
    v.body[row + 1][3] = SA.newCell('plate', 1);
    assert(near(SA.V.stats(v).topSpeed / plain, 0.7), '同侧多片不能重复扣速');
    v.body[row][4 + width] = SA.newCell('armor', 1);
    assert(!SA.V.issues(v).length, `${chassis} 两端挂甲应通过出战检查`);
    assert(near(SA.V.stats(v).topSpeed / plain, 0.4), '双侧挂甲应减速 60%');
    const front = v.body[row][4 + width];
    front.hp = 0;
    assert(near(SA.V.stats(v).topSpeed / plain, 0.7), '毁掉一侧挂甲应解除该侧罚速');
    const roof = car(chassis);
    roof.body[row - 2][4 + width] = SA.newCell('armor', 1);
    assert(near(SA.V.stats(roof).armorSpeedFactor, 1), '常规顶部装甲不应减速');
  }
  const biped = SA.V.create('双足原规则');
  biped.body[SA.V.chassisRow('biped')][4] = SA.newCell('biped', 1);
  assert(!SA.V.canPlace(biped, 'armor', row, 3).ok, '双足腿区不能借端甲规则挂甲');
  assert(near(SA.V.stats(biped).armorSpeedFactor, 1), '双足不受端甲减速');
  const boilerMod = SA.mod(SA.newCell('boiler', 1)), boilerSupply = boilerMod.supply;
  for (const supply of [4, 1000]) {
    boilerMod.supply = supply;
    const v = car('track');
    const plain = SA.V.stats(v);
    assert(supply === 4 ? plain.speedMul < 1 : near(plain.speedMul, SA.K.SPEED_BOOST), '夹具应覆盖动力不足和富余');
    v.body[row][3] = SA.newCell('plate', 1);
    let stats = SA.V.stats(v);
    assert(near(stats.topSpeed / (stats.speed * stats.speedMul), 0.7), '端甲减速不应被动力倍率冲抵');
    v.body[row][6] = SA.newCell('armor', 1);
    stats = SA.V.stats(v);
    assert(near(stats.topSpeed / (stats.speed * stats.speedMul), 0.4), '双端减速不应被动力倍率冲抵');
  }
  boilerMod.supply = boilerSupply;
  const battleCar = car('track');
  battleCar.body[row][3] = SA.newCell('plate', 1);
  battleCar.body[row][6] = SA.newCell('armor', 1);
  SA.S.load().vehicle = battleCar;
  SA.go = () => {};
  SA.Battle.startState({ mode: 'friendly', enemyVehicle: car('track'), enemyName: '测试对手', terrain: 'flat' });
  const state = SA.Battle.debug.B, side = state.p;
  assert(near(side.armorSpeedFactor, 0.4), '战斗开局应计入双端挂甲');
  SA.Battle.debug.step(1 / 60);
  assert(near(side.armorSpeedFactor, 0.4), '每帧速度应继续计入双端挂甲');
  SA.Battle.debug.damage('p', row, 6 + state.pShift, 'body', 9999);
  SA.Battle.debug.step(1 / 60);
  assert(near(side.armorSpeedFactor, 0.7), '战斗毁掉前甲应恢复单侧速度');
  SA.Battle.debug.damage('p', row, 3 + state.pShift, 'body', 9999);
  SA.Battle.debug.step(1 / 60);
  assert(near(side.armorSpeedFactor, 1), '战斗毁掉两端装甲应恢复原速');
  // 边界原语只在传入左右世界坐标时生效；连同车身外沿一起限制。
  const cell = SA.K.CELL, pad = SA.SPR.PADX, enemy = state.e;
  const playerLeft = () => side.x + pad + side.minCol * cell;
  const enemyRight = () => enemy.x + SA.K.COLS * cell + pad - enemy.minCol * cell;
  state.bounds = { left: playerLeft() - 5, right: enemyRight() + 5 };
  side.x -= 50; side.vx = -20;
  enemy.x += 50; enemy.vx = 20;
  SA.Battle.debug.step(1 / 60);
  assert(playerLeft() >= state.bounds.left - 1e-9 && side.vx >= 0, '玩家车外沿越过左边界');
  assert(enemyRight() <= state.bounds.right + 1e-9 && enemy.vx <= 0, '敌车外沿越过右边界');
  state.keys.left = true;
  SA.Battle.debug.step(1);
  assert(playerLeft() >= state.bounds.left - 1e-9, '持续向外驾驶不能穿过边界');
  state.keys.left = false; state.keys.right = true;
  SA.Battle.debug.step(2);
  assert(playerLeft() > state.bounds.left + 1, '掉头向内后应能离开边界');
  state.keys.right = false;
  // 把车头放到刚接触的位置，下一帧碰撞分离后也应重新限制左侧外沿。
  const enemyFrontOffset = SA.K.COLS * cell + pad - (enemy.frontCol + 1) * cell;
  const playerFront = () => side.x + pad + (side.frontCol + 1) * cell;
  enemy.x = playerFront() - 10 - enemyFrontOffset;
  state.bounds.left = playerLeft() - 1;
  state.bounds.right = enemyRight() + 100;
  SA.Battle.debug.step(1 / 60);
  assert(playerLeft() >= state.bounds.left - 1e-9, '碰撞分离后不能把玩家车挤出左边界');
  const oldBounds = SA.CAMPAIGN[0].bounds, oldStart = SA.Battle.start;
  const sampleBounds = { left: -600, right: 1800 };
  SA.CAMPAIGN[0].bounds = sampleBounds;
  let started;
  SA.Battle.start = options => { started = options; };
  const entry = SA.S.arenaEntries('camp').find(item => item.key === '0,0');
  assert.strictEqual(entry.bounds, sampleBounds, '战役列表应携带所属章节边界');
  entry.start();
  assert.strictEqual(started.bounds, sampleBounds, '战役开战应传入所属章节边界');
  SA.Battle.start = oldStart;
  if (oldBounds === undefined) delete SA.CAMPAIGN[0].bounds;
  else SA.CAMPAIGN[0].bounds = oldBounds;
  const quadCar = car('quad');
  quadCar.body[row][8] = SA.newCell('quad', 1);
  quadCar.body[row][3] = SA.newCell('plate', 1);
  quadCar.body[row][12] = SA.newCell('armor', 1);
  SA.S.d.vehicle = quadCar;
  SA.Battle.startState({ mode: 'friendly', enemyVehicle: car('track'), enemyName: '测试对手', terrain: 'flat' });
  const quadBattle = SA.Battle.debug.B;
  SA.Battle.debug.damage('p', row, 8 + quadBattle.pShift, 'body', 9999);
  SA.Battle.debug.step(1 / 60);
  assert(quadBattle.p.speed > 0 && near(quadBattle.p.armorSpeedFactor, 0.4), '四足部分底盘损毁后，存活端甲仍应按两侧罚速');
  const quadLeft = () => quadBattle.p.x + pad + quadBattle.p.minCol * cell;
  quadBattle.bounds = { left: quadLeft() - 2, right: quadBattle.e.x + 2000 };
  quadBattle.p.x -= 20; quadBattle.p.vx = -10;
  SA.Battle.debug.step(1 / 60);
  assert(quadLeft() >= quadBattle.bounds.left - 1e-9, '串联四足底盘也应按整车外沿限位');
  // 蒸汽撞锤会在普通碰撞后施加外向冲量；有限场地仍须在同一帧收住车速。
  const pistonCar = car('track');
  pistonCar.body[row][6] = SA.newCell('piston', 1);
  SA.S.d.vehicle = pistonCar;
  SA.Battle.startState({ mode: 'friendly', enemyVehicle: car('track'), enemyName: '边界对手', terrain: 'flat' });
  const pistonBattle = SA.Battle.debug.B, p = pistonBattle.p, e = pistonBattle.e;
  const front = p.x + pad + (p.frontCol + 1) * cell;
  e.x = front - (SA.K.COLS * cell + pad - (e.frontCol + 1) * cell);
  const edge = () => e.x + SA.K.COLS * cell + pad - e.minCol * cell;
  pistonBattle.bounds = { left: -1000, right: edge() - 1 };
  SA.Battle.debug.step(1 / 60);
  assert(p.events.knock > 0, '夹具应真实触发蒸汽撞锤冲量');
  assert(edge() <= pistonBattle.bounds.right + 1e-9 && e.vx <= 0, '活塞推挤后敌车不能穿过右边界');
  return { chassis: ['track', 'quad'], sides: ['rear', 'front'], armor: ['plate', 'armor', 'armor_heavy'] };
}

if (require.main === module) console.log(JSON.stringify(run(), null, 2));
module.exports = { run };
